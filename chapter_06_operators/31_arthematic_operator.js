// Arithmetic Operators

let a = 10, b = 3;
console.log(a);
console.log(b);

let sum = a + b;
let sub = a - b;
let mul = a * b;
let div = a / b;

console.log(sum);
console.log(sub);
console.log(mul);
console.log(div);
